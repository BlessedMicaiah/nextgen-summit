"""Generate a rotated People's Choice admin credential, without the PIN leaving this machine.

    python tools/make-admin-pin.py

It asks for the new PIN twice, without echoing it, and writes ONE file:

    release/config.admin.php     (gitignored; upload it, then delete it)

That file holds a random salt and a salted HMAC of the PIN. It does not hold the PIN, and
neither does this script's output, your terminal scrollback, or any log. Nothing is sent
anywhere -- there is no network call in this file.

WHERE IT GOES

Upload it with the Hostinger File Manager to the data directory, which sits BESIDE the web
root, not inside it:

    /home/u382065856/domains/nextgensummit.us/nextgen-data/config.admin.php

Not public_html. The whole point of that directory is that a deploy cannot reach it, which
is why a rotated PIN survives every future release.

WHAT IT CHANGES, AND WHAT IT DOES NOT

Only the People's Choice dashboard reads this file. The registrations tool at /admin/ never
looks at it -- it always checks config.php -- so rotating here CANNOT lock out anyone who
uses the registrations tool. That is deliberate: it is the safe half to change.

Deleting the file restores the config.php PIN. That is the undo.

Because config.php keeps working as a fallback for People's Choice if this file ever becomes
unreadable, the old PIN is not destroyed by this. Rotating config.php itself is a separate,
later job.
"""
import getpass
import hashlib
import hmac
import io
import os
import secrets
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'release', 'config.admin.php')

# The server computes hash_hmac('sha256', $pin, $salt): the SALT is the key, the PIN is the
# message. Getting those the wrong way round produces a file that writes cleanly and then
# refuses every password, so it is checked below against a published vector before use.
def mac(pin: str, salt: str) -> str:
    return hmac.new(salt.encode('utf-8'), pin.encode('utf-8'), hashlib.sha256).hexdigest()


def selftest() -> None:
    """RFC 4231 test case 2. PHP's hash_hmac and this agree, or we stop here."""
    got = mac('what do ya want for nothing?', 'Jefe')
    want = '5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843'
    if got != want:
        sys.exit('HMAC self-test failed; refusing to write a credential.')
    print('  HMAC self-test (RFC 4231 case 2): ok')


def main() -> None:
    print(__doc__.split('WHERE IT GOES')[0].rstrip())
    print()
    selftest()
    print()

    pin = getpass.getpass('  New admin PIN (not shown, min 8 characters): ')
    if len(pin) < 8:
        sys.exit('  Too short. The server rejects anything under 8 characters. Nothing written.')
    if len(pin) > 200:
        sys.exit('  Too long (max 200). Nothing written.')
    if not pin.strip():
        sys.exit('  A PIN of only spaces will not do. Nothing written.')
    again = getpass.getpass('  Type it again to confirm:                   ')
    if not hmac.compare_digest(pin, again):
        sys.exit('  They do not match. Nothing written.')

    salt = secrets.token_hex(32)
    digest = mac(pin, salt)
    del pin, again

    body = '\n'.join([
        '<?php',
        "/* Rotated NextGen admin PIN. Generated by tools/make-admin-pin.py, outside the web",
        '   root, never in git and never in a release archive. It holds a salted HMAC of the',
        '   PIN and never the PIN. Deleting this file restores the config.php PIN. */',
        'declare(strict_types=1);',
        '',
        "const NGS_ADMIN_SALT_V2 = '%s';" % salt,
        "const NGS_ADMIN_HASH_V2 = '%s';" % digest,
        '',
        '/* Sessions opened before this moment are no longer authenticated. */',
        'const NGS_ADMIN_EPOCH = %d;' % int(__import__('time').time()),
        '',
    ])

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(body)
    try:
        os.chmod(OUT, 0o600)
    except OSError:
        pass

    print()
    print('  Written: %s' % OUT)
    print('  It contains a salt and a hash. It does not contain your PIN.')
    print()
    print('  Next:')
    print('   1. Hostinger -> File Manager -> open')
    print('        /home/u382065856/domains/nextgensummit.us/nextgen-data/')
    print('      (BESIDE public_html, not inside it)')
    print('   2. Upload config.admin.php there. Overwrite if one already exists.')
    print('   3. Sign in at https://nextgensummit.us/pitch/peoples-choice/admin/')
    print('      The login screen should now read "rotated file (outside the web root)".')
    print('   4. Delete the local copy: rm release/config.admin.php')
    print()
    print('  To undo: delete config.admin.php on the server. The config.php PIN returns.')


if __name__ == '__main__':
    main()
