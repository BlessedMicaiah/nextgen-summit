<?php
/* ============================================================================
   Create a NextGen Data leadership account.

       php tools/make-ngd-user.php <username> ["Display Name"] [--emails]

   --emails grants permission to download real voter email addresses. It is a separate
   permission from reading the dashboard, and it is off unless you ask for it.

   Prints a freshly generated passphrase ONCE, to this terminal, and writes only its
   bcrypt hash into public/api/config.ngd.php. The passphrase is never stored, never
   logged and never committed: if it is lost, run this again and the old one stops
   working.

   WHY THE HASH GOES IN A CONFIG FILE RATHER THAN THE LIVE ACCOUNT STORE

   The account store (ngd-users.json) lives outside the web root, where a deploy cannot
   reach it -- which is right for accounts the owner adds from the dashboard, and useless
   for provisioning the first one, because there is no way to put a file there without a
   shell. A deploy CAN carry public/api/config.ngd.php, api/.htaccess already refuses to
   serve anything matching config.*.php, and .gitignore already keeps config.*.php out of
   the repository. So the file rides along with the release, is unreadable over the web,
   and never reaches GitHub.

   WHAT THE FILE CONTAINS, AND DOES NOT

   One line per account: the username, a display name, and a bcrypt hash. Bcrypt is a
   one-way function with a per-account salt and a work factor; the file is not a secret in
   the sense a password is, and someone who reads it still cannot sign in. It is treated as
   private anyway, because there is no reason not to.

   Accounts defined here can be SUSPENDED from the dashboard but not deleted, because the
   next deploy would bring them back and a delete that silently undoes itself is worse than
   no delete at all. To remove one for good, take its line out of this file and redeploy.
   ========================================================================= */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
$file = $root . '/public/api/config.ngd.php';

$args = array_slice($argv, 1);
$wantEmails = in_array('--emails', $args, true);
$args = array_values(array_filter($args, static fn($a) => $a !== '--emails'));
$user = strtolower(trim((string) ($args[0] ?? '')));
$name = trim((string) ($args[1] ?? ''));

if ($user === '' || !preg_match('/^[a-z0-9][a-z0-9._-]{1,30}$/', $user)) {
    fwrite(STDERR, "usage: php tools/make-ngd-user.php <username> [\"Display Name\"]\n"
        . "  username: letters, numbers, dot, dash, underscore; 2 to 31 characters\n");
    exit(1);
}
if ($name === '') {
    $name = ucfirst($user);
}

/* A passphrase of real words is both stronger than it looks and possible to read down a
   phone line, which is how this one will actually be delivered. Five words from this list
   is about 64 bits; the digits are there for password fields that demand one. */
$words = ['amber', 'anchor', 'atlas', 'badge', 'ballot', 'beacon', 'bridge', 'canvas',
          'cedar', 'cobalt', 'compass', 'copper', 'cotton', 'crimson', 'delta', 'ember',
          'falcon', 'forest', 'garnet', 'granite', 'harbor', 'hollow', 'indigo', 'ivory',
          'jasper', 'juniper', 'kestrel', 'lantern', 'legacy', 'lumen', 'marble', 'meadow',
          'meteor', 'mosaic', 'nectar', 'nimbus', 'orchid', 'otter', 'pebble', 'pennant',
          'pioneer', 'quartz', 'quiver', 'ribbon', 'river', 'saffron', 'signal', 'silver',
          'solace', 'summit', 'thistle', 'timber', 'topaz', 'tundra', 'velvet', 'willow',
          'winter', 'zenith'];
$pick = [];
for ($i = 0; $i < 5; $i++) {
    $pick[] = $words[random_int(0, count($words) - 1)];
}
$pass = implode('-', $pick) . '-' . random_int(10, 99);

$hash = password_hash($pass, PASSWORD_DEFAULT);
if (!is_string($hash) || $hash === '' || !password_verify($pass, $hash)) {
    fwrite(STDERR, "This PHP could not hash the passphrase. Nothing was written.\n");
    exit(1);
}

/* Read what is already there, drop any line for this username, and write the rest back. */
$keep = [];
if (is_file($file)) {
    foreach (explode("\n", (string) @file_get_contents($file)) as $line) {
        if (preg_match("/^\\s*NGD_ACCOUNT\\s*=\\s*'([^'|]+)\\|/", $line, $m)) {
            if (strtolower($m[1]) === $user) {
                continue;                       // replaced below
            }
            $keep[] = rtrim($line);
        }
    }
}
$keep[] = "NGD_ACCOUNT = '" . $user . '|' . str_replace(['|', "'", "
"], ' ', $name)
        . '|' . $hash . ($wantEmails ? '|emails' : '') . "';";

$body = "<?php\n"
      . "/* NextGen Data leadership accounts. Generated by tools/make-ngd-user.php.\n"
      . "   Never committed (.gitignore: public/api/config.*.php), never served\n"
      . "   (api/.htaccess: config.*.php is denied), carried by the release archive.\n"
      . "   One line per account: username|display name|bcrypt hash. Read as text, never\n"
      . "   executed -- see ngd_seed_accounts() in ngd-auth.php. */\n"
      . "declare(strict_types=1);\n\n"
      . implode("\n", $keep) . "\n";

$tmp = $file . '.' . bin2hex(random_bytes(4)) . '.tmp';
if (@file_put_contents($tmp, $body, LOCK_EX) === false || !@rename($tmp, $file)) {
    @unlink($tmp);
    fwrite(STDERR, "Could not write $file\n");
    exit(1);
}
@chmod($file, 0640);

$line = str_repeat('=', 66);
echo "\n$line\n";
echo "  Account ready:  $user   ($name)\n";
echo "  Passphrase:     $pass\n";
echo "$line\n";
echo "  This is the only time it is shown. It is not stored anywhere -- only its\n";
echo "  bcrypt hash, in public/api/config.ngd.php, which is gitignored and is never\n";
echo "  served over the web.\n\n";
echo "  The account exists on a site once that file is in the release archive:\n";
echo "      python -I tools/release.py staging\n";
echo "      node tools/deploy.mjs staging.nextgensummit.us release/staging-<sha>.zip\n\n";
echo "  Sign in at /insights/ with the username above. Suspend it from Settings;\n";
echo "  to remove it for good, delete its line from config.ngd.php and redeploy.\n\n";
